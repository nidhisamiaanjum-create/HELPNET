/* ============================================================
   STORAGE
   ============================================================ */


const LANG_KEY = "helpnet_lang";
let applyingLanguage = false;




/* ============================================================
   GET CURRENT LANGUAGE
   ============================================================ */


function getLanguage() {


    const savedLanguage = localStorage.getItem(LANG_KEY);


    if (savedLanguage === "en") {
        return "en";
    }


    return "bn";
}




/* ============================================================
   GET TRANSLATION
   ============================================================ */


function t(key) {


    const language = getLanguage();


    if (
        TEXT[language] &&
        TEXT[language][key]
    ) {
        return TEXT[language][key];
    }


    if (TEXT.bn[key]) {
        return TEXT.bn[key];
    }


    return key;
}




/* ============================================================
   APPLY LANGUAGE
   ============================================================ */


function applyLanguage() {

    if (applyingLanguage) {
        return;
    }

    applyingLanguage = true;
    try {

    const language = getLanguage();


    console.log("HELPNET language:", language);


    /* Change HTML language */
    document.documentElement.lang = language;




    /* -----------------------------------------
       Normal text
       ----------------------------------------- */


    const elements = document.querySelectorAll("[data-i18n]");


    console.log(
        "HELPNET translation elements:",
        elements.length
    );




    elements.forEach(function (element) {


        const key = element.getAttribute("data-i18n");


        const translation = t(key);


        if (
            element.tagName === "INPUT" ||
            element.tagName === "TEXTAREA"
        ) {


            element.placeholder = translation;


        } else {


            element.textContent = translation;


        }


    });




    /* -----------------------------------------
       Placeholder translations
       ----------------------------------------- */


    const placeholderElements =
        document.querySelectorAll(
            "[data-i18n-placeholder]"
        );




    placeholderElements.forEach(function (element) {


        const key =
            element.getAttribute(
                "data-i18n-placeholder"
            );


        element.placeholder = t(key);


    });




    /* -----------------------------------------
       Language button
       ----------------------------------------- */


    const button =
        document.getElementById("langToggle");




    if (button) {


        button.textContent =
            t("langButton");


    }

    document.dispatchEvent(new CustomEvent("helpnet:languagechange", {
        detail: { language: language }
    }));

    } finally {
        applyingLanguage = false;
    }

}




/* ============================================================
   TOGGLE LANGUAGE
   ============================================================ */


function toggleLanguage() {


    const currentLanguage = getLanguage();


    let newLanguage;


    if (currentLanguage === "bn") {


        newLanguage = "en";


    } else {


        newLanguage = "bn";


    }




    console.log(
        "Changing language:",
        currentLanguage,
        "→",
        newLanguage
    );




    /* Save language */
    localStorage.setItem(
        LANG_KEY,
        newLanguage
    );




    /* Apply immediately */
    applyLanguage();


}




/* ============================================================
   SET LANGUAGE
   ============================================================ */


function setLanguage(language) {


    if (
        language !== "bn" &&
        language !== "en"
    ) {


        return;


    }




    localStorage.setItem(
        LANG_KEY,
        language
    );




    applyLanguage();


}




/* ============================================================
   PAGE LOAD
   ============================================================ */


function initializeI18n() {


        console.log(
            "HELPNET i18n.js loaded successfully"
        );




        /* Apply default language */
        applyLanguage();

        if (document.body && !window.helpnetTranslationObserver) {
            window.helpnetTranslationObserver = new MutationObserver(
                function (mutations) {
                    const hasTaggedContent = mutations.some(function (mutation) {
                        return Array.from(mutation.addedNodes).some(function (node) {
                            return node.nodeType === Node.ELEMENT_NODE &&
                                (node.matches("[data-i18n], [data-i18n-placeholder]") ||
                                 node.querySelector("[data-i18n], [data-i18n-placeholder]"));
                        });
                    });
                    if (hasTaggedContent) applyLanguage();
                }
            );
            window.helpnetTranslationObserver.observe(document.body, {
                childList: true,
                subtree: true
            });
        }



        /* Language button */
        const button =
            document.getElementById(
                "langToggle"
            );




        if (button) {


            button.addEventListener(
                "click",
                toggleLanguage
            );


            console.log(
                "HELPNET language button connected"
            );


        } else {


            console.error(
                "HELPNET: langToggle button not found"
            );


        }


}


/* The home page loads this script at the end of <body>, while other
   pages may load it after DOMContentLoaded. Support both cases. */
if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", initializeI18n, { once: true });
} else {
    initializeI18n();
}
