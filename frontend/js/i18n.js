/* ============================================================
   STORAGE
   ============================================================ */


const LANG_KEY = "helpnet_lang";




/* ============================================================
   GET CURRENT LANGUAGE
   ============================================================ */


function getLanguage() {


    const savedLanguage = localStorage.getItem(LANG_KEY);


    if (savedLanguage === "en") {
        return "en";
    }


    return "bn";
}




/* ============================================================
   GET TRANSLATION
   ============================================================ */


function t(key) {


    const language = getLanguage();


    if (
        TEXT[language] &&
        TEXT[language][key]
    ) {
        return TEXT[language][key];
    }


    if (TEXT.bn[key]) {
        return TEXT.bn[key];
    }


    return key;
}




